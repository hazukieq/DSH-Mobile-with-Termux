/**
 * Build the browser half of dsh-mobile-ui.
 *
 * Source layout:
 *   src/runtime.js  — DOM/CSS logic, a plain `function createMobileUi()` IIFE body
 *   src/mobile.css  — the mobile stylesheet
 *
 * Output: lib/client.js — a classic script that registers one factory with the
 * shell's lazy CJS module table (`window.__ModuleLoader__.load`), the same shape
 * the shipped client bundles use. build.mjs also exports `assembleBundle()` for
 * dev-proxy.mjs, so the live preview always serves the exact production bundle.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('./', import.meta.url)
export const PACKAGE_ID = 'dsh-mobile-ui'
/** Wrapper-shell revision folded into the bundle revision. */
export const WRAPPER_VERSION = '2'

/** Read one source file as UTF-8. */
function read(relative) {
  return readFileSync(new URL(relative, ROOT), 'utf8')
}

/**
 * Compose the client bundle.
 * @returns {{ code: string, rev: string }} executable bundle text and its revision.
 */
export function assembleBundle() {
  const runtime = read('src/runtime.js')
  const css = read('src/mobile.css')
  const rev = createHash('sha1')
    .update(WRAPPER_VERSION)
    .update('\0')
    .update(runtime)
    .update('\0')
    .update(css)
    .digest('hex')
    .slice(0, 12)

  const code = [
    '/* dsh-mobile-ui — generated by build.mjs; do not edit lib/client.js directly. */',
    'window.__ModuleLoader__.load({',
    '  id: ' + JSON.stringify(PACKAGE_ID) + ',',
    '  factory: function (require) {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
    '    var DSH_MOBILE_CSS = ' + JSON.stringify(css) + ';',
    runtime,
    '    var runtime;',
    '    try {',
    '      runtime = createMobileUi();',
    '    } catch (error) {',
    '      try { console.error("[dsh-mobile-ui] runtime creation failed", error); } catch (ignored) {}',
    '      runtime = { apply: function () {}, version: "failed" };',
    '    }',
    '    exports.apply = function (ctx) {',
    '      try {',
    '        var diag = typeof window !== "undefined" ? window.__DSH_MOBILE_DIAG__ : void 0;',
    '        runtime.apply(ctx, DSH_MOBILE_CSS, diag);',
    '      } catch (error) {',
    '        try { console.error("[dsh-mobile-ui] apply failed", error); } catch (ignored) {}',
    '      }',
    '    };',
    '    exports.inject = [];',
    '    exports.version = runtime.version;',
    '    return module.exports;',
    '  }',
    '});',
    ''
  ].join('\n')

  return { code, rev }
}

/** Client bundle written by `node build.mjs`. */
export function writeBundle() {
  const { code, rev } = assembleBundle()
  const target = new URL('lib/client.js', ROOT)
  writeFileSync(target, code)
  return { path: fileURLToPath(target), rev, bytes: Buffer.byteLength(code) }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = writeBundle()
  console.log('built ' + result.path + ' rev=' + result.rev + ' bytes=' + result.bytes)
}

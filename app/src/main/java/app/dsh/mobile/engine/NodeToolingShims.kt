package app.dsh.mobile.engine

internal object NodeToolingShims {
    fun script(tool: String): String {
        require(tool in listOf("corepack", "npm", "npx", "pnpm"))
        val candidates = when (tool) {
            "corepack" -> "\"\$base/../lib/node_modules/corepack/dist/corepack.js\""
            "npm" -> "\"\$base/../lib/node_modules/npm/bin/npm-cli.js\" \"\$base/../lib/node_modules/corepack/dist/npm.js\""
            "npx" -> "\"\$base/../lib/node_modules/npm/bin/npx-cli.js\" \"\$base/../lib/node_modules/corepack/dist/npx.js\""
            else -> "\"\${DSH_HOME:-\$base/../../dsh-home}/profiles/web/node_modules/pnpm/bin/pnpm.cjs\" \"\${DSH_HOME:-\$base/../../dsh-home}/profiles/web/node_modules/pnpm/bin/pnpm.mjs\" \"\$base/../lib/node_modules/corepack/dist/pnpm.js\""
        }
        val override = "DSH_${tool.uppercase()}_CLI"
        val launch = "exec \"\$base/node\" \"\$cli\" \"\$@\""
        return """
            |#!/system/bin/sh
            |# generated by DSH Mobile
            |base=${'$'}(CDPATH= cd -- "${'$'}(dirname -- "${'$'}0")" && pwd)
            |if [ -n "${'$'}{$override:-}" ]; then
            |  cli="${'$'}$override"
            |  [ -f "${'$'}cli" ] || { echo "$tool: $override not found: ${'$'}cli" >&2; exit 127; }
            |  $launch
            |fi
            |for cli in $candidates; do
            |  [ -f "${'$'}cli" ] && $launch
            |done
            |echo "$tool: no bundled CLI found; set $override to an installed CLI path (see ENGINE-BUILD.md)." >&2
            |exit 127
            |
        """.trimMargin()
    }
}
